#!/bin/bash
# network/mac_clone.sh
#
# Clones a target MAC address onto IFACE_TARGET so the device presents the
# same L2 identity the original host used, keeping the tap transparent to
# any downstream MAC-filtering/port-security or ARP-caching equipment.
#
# Two strategies are supported:
#   1. macchanger (runtime, immediate, applied by setup.sh / this script)
#   2. systemd.link (boot-time, persists across reboots without this script)
#
# Usage:
#   sudo ./network/mac_clone.sh                  # auto-learn host MAC, apply now
#   sudo ./network/mac_clone.sh aa:bb:cc:dd:ee:ff # clone an explicit MAC, apply now
#   sudo ./network/mac_clone.sh --persist         # also write a systemd.link file

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../config/pi-squirrel.conf
source "${REPO_ROOT}/config/pi-squirrel.conf"
# shellcheck source=./ifaces.sh
source "${REPO_ROOT}/network/ifaces.sh"

if [[ $EUID -ne 0 ]]; then
    echo "ERROR: must be run as root (sudo)." >&2
    exit 1
fi

PERSIST=false
MAC_ARG=""
for arg in "$@"; do
    case "$arg" in
        --persist) PERSIST=true ;;
        *) MAC_ARG="$arg" ;;
    esac
done

detect_physical_ifaces

if [[ "${MAC_CLONE_ENABLED}" != "true" ]]; then
    echo "MAC_CLONE_ENABLED=false in config/pi-squirrel.conf, nothing to do."
    exit 0
fi

# Resolve the MAC to clone, in priority order: CLI arg > config value >
# auto-learned from live traffic on IFACE_HOST.
TARGET_MAC="${MAC_ARG:-${TARGET_HOST_MAC:-}}"

learn_mac_from_traffic() {
    local iface="$1"
    echo "Learning original host MAC by sniffing 5s of traffic on ${iface}..." >&2
    command -v tcpdump >/dev/null 2>&1 || { echo "ERROR: tcpdump required for MAC auto-learn." >&2; return 1; }
    timeout 5 tcpdump -i "$iface" -e -c 20 2>/dev/null \
        | grep -oE '([0-9a-f]{2}:){5}[0-9a-f]{2}' \
        | sort | uniq -c | sort -rn | awk '{print $2}' | head -n1
}

if [[ -z "$TARGET_MAC" ]]; then
    TARGET_MAC="$(learn_mac_from_traffic "${IFACE_HOST}" || true)"
fi

if [[ -z "$TARGET_MAC" ]]; then
    echo "ERROR: no MAC address resolved (none supplied, none configured, none learned)." >&2
    exit 1
fi

if ! [[ "$TARGET_MAC" =~ ^([0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}$ ]]; then
    echo "ERROR: '${TARGET_MAC}' is not a valid MAC address." >&2
    exit 1
fi

echo "Cloning MAC ${TARGET_MAC} onto ${IFACE_TARGET}..."
if command -v macchanger >/dev/null 2>&1; then
    ip link set dev "${IFACE_TARGET}" down
    macchanger -m "${TARGET_MAC}" "${IFACE_TARGET}"
    ip link set dev "${IFACE_TARGET}" up
else
    # Fallback to plain iproute2 if macchanger isn't installed.
    ip link set dev "${IFACE_TARGET}" down
    ip link set dev "${IFACE_TARGET}" address "${TARGET_MAC}"
    ip link set dev "${IFACE_TARGET}" up
fi

echo "${TARGET_MAC}" > /etc/pi-squirrel/cloned-mac.env

if [[ "$PERSIST" == "true" ]]; then
    install -d -m 0755 /etc/systemd/network
    LINK_FILE="/etc/systemd/network/10-pi-squirrel-${IFACE_TARGET}.link"
    cat >"${LINK_FILE}" <<EOF
# Generated by network/mac_clone.sh --persist
# Pins ${IFACE_TARGET} to the cloned MAC address at boot, before the
# packet-tap bridge is brought up.
[Match]
OriginalName=${IFACE_TARGET}

[Link]
MACAddress=${TARGET_MAC}
EOF
    echo "Wrote persistent systemd.link config: ${LINK_FILE}"
    echo "(Run 'sudo udevadm control --reload' or reboot to apply on next boot.)"
fi

ip -br link show "${IFACE_TARGET}"
